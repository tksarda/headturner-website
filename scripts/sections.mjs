// Prints an overview of the page's sections (what's shown, what's hidden, what each needs)
// and writes the same overview to SECTIONS.md. Run: npm run sections
import { readFileSync, writeFileSync } from 'node:fs';

const { items } = JSON.parse(readFileSync(new URL('../src/data/sections.json', import.meta.url), 'utf8'));
const status = (i) => (i.show ? 'SHOWN' : 'HIDDEN');
const sections = items.filter((i) => i.type === 'section');
const partsOf = (key) => items.filter((i) => i.parent === key);

const rows = [];
let n = 0;
for (const s of sections) {
  rows.push({ n: ++n, name: s.name, status: status(s), edit: s.content, needs: s.needs || '', placeholder: s.placeholder, indent: false });
  for (const p of partsOf(s.key)) rows.push({ n: '', name: p.name, status: status(p), edit: p.content, needs: p.needs || '', placeholder: p.placeholder, indent: true });
}

// Terminal output
const pad = (s, w) => String(s).padEnd(w);
const w = { n: 3, name: Math.max(...rows.map((r) => r.name.length + (r.indent ? 3 : 0))), status: 6 };
console.log('\nHeadturner page overview (in page order). Switch sections on or off in src/data/sections.json\n');
for (const r of rows) console.log(`${pad(r.n, w.n)} ${pad((r.indent ? '   ' : '') + r.name, w.name)}  ${pad(r.status, w.status)}  ${r.placeholder ? 'placeholder' : ''}`);
const hidden = rows.filter((r) => r.status === 'HIDDEN');
console.log(`\n${rows.length - hidden.length} shown, ${hidden.length} hidden.\n`);

// SECTIONS.md
const esc = (s) => String(s).replaceAll('|', '\\|');
const lines = [
  '# Page overview',
  '',
  'Generated by `npm run sections` from `src/data/sections.json`. Do not edit by hand: change `sections.json`, then run the command again.',
  '',
  'The page, in order. Hidden sections are not in the published page at all.',
  '',
  '| # | Section | Status | Edit it in | Still to do |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.n} | ${r.indent ? '↳ ' : ''}${esc(r.name)} | ${r.status === 'SHOWN' ? 'Shown' : '**Hidden**'}${r.placeholder ? ' (placeholder)' : ''} | ${esc(r.edit)} | ${esc(r.needs)} |`),
  '',
  `${rows.length - hidden.length} shown, ${hidden.length} hidden.`,
  '',
];
writeFileSync(new URL('../SECTIONS.md', import.meta.url), lines.join('\n'));
